
let money = 3000;        // деньги в тенге
let age = 10;          // возраст
let freeTime = 1;     // свободное время в часах

// Чтобы пойти в кино, нужно выполнить ВСЕ условия:
// иметь минимум 3000 тенге И быть старше 10 лет
// И иметь минимум 2 часа свободного времени

if (money >= 3000 && age >= 10 && freeTime >= 2){
    console.log("Можно идти в кино")
}else{
    console.log("Идти в кино нельзя")
}
